use regex::Regex;
use roxmltree::Document;
use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};

const STYLES: &[&str] = &["solid", "regular", "brands"];
const CURRENT_DIRECTORY: &str = "fontawesome";
const LEGACY_DIRECTORY: &str = "fontawesome-legacy";

lazy_static::lazy_static! {
    static ref PATH_FILL: Regex = Regex::new(r#"(?i)\s+fill=(?:'currentcolor'|"currentcolor")"#).unwrap();
    static ref ICON_ID: Regex = Regex::new(r"^[a-z0-9]+(?:-[a-z0-9]+)*$").unwrap();
}

const LEGACY_HEADER: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<!--
Icon names no longer in Font Awesome Free, kept for backwards compatibility.
Generated by `bin/rake svgicons:update`, do not edit by hand.
License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
-->
<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">
"#;

#[derive(Debug)]
pub struct UnsafeSpriteError(String);

impl std::fmt::Display for UnsafeSpriteError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}
impl std::error::Error for UnsafeSpriteError {}

pub struct FontAwesomeSync {
    package_path: PathBuf,
    vendor_path: PathBuf,
}

impl FontAwesomeSync {
    pub fn new(package_path: PathBuf, vendor_path: PathBuf) -> Self {
        Self {
            package_path,
            vendor_path,
        }
    }

    pub fn files(&self) -> Result<HashMap<PathBuf, Option<String>>, Box<dyn std::error::Error>> {
        let mut files = HashMap::new();

        let aliases = self.aliases()?;

        for &style in STYLES {
            let upstream_path = self.package_path.join(format!("sprites/{}.svg", style));
            let upstream_content = fs::read_to_string(&upstream_path)?;
            let upstream = PATH_FILL.replace_all(&upstream_content, "").to_string();

            let upstream_symbols = self.symbols(&upstream);
            self.verify(style, &upstream_symbols, &upstream)?;

            let current_path = self.current_path(style);
            files.insert(current_path, Some(upstream.clone()));

            let legacy_path = self.legacy_path(style);
            let legacy_content =
                self.legacy_sprite(style, &upstream_symbols, &upstream, &aliases)?;
            files.insert(legacy_path, legacy_content);
        }

        Ok(files)
    }

    pub fn stale_files(&self) -> Result<Vec<PathBuf>, Box<dyn std::error::Error>> {
        let mut stale = Vec::new();
        let files = self.files()?;

        for (path, content_opt) in files {
            let current = if path.exists() {
                Some(fs::read_to_string(&path)?)
            } else {
                None
            };

            if current != content_opt {
                stale.push(path);
            }
        }

        stale.sort();
        Ok(stale)
    }

    pub fn write(&self) -> Result<(), Box<dyn std::error::Error>> {
        let files = self.files()?;

        for (path, content_opt) in files {
            if let Some(content) = content_opt {
                if let Some(parent) = path.parent() {
                    fs::create_dir_all(parent)?;
                }
                fs::write(&path, content)?;
            } else if path.exists() {
                fs::remove_file(&path)?;
            }
        }
        Ok(())
    }

    fn verify(
        &self,
        style: &str,
        _symbols: &HashMap<String, String>,
        full_xml: &str,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let mut unsafe_icons = Vec::new();
        let doc = Document::parse(full_xml)?;

        for node in doc.descendants().filter(|n| n.has_tag_name("symbol")) {
            let id = node.attribute("id").unwrap_or("");
            if !self.safe_symbol(&node) {
                unsafe_icons.push(id.to_string());
            }
        }

        if !unsafe_icons.is_empty() {
            unsafe_icons.truncate(10);
            return Err(Box::new(UnsafeSpriteError(format!(
                "{}.svg has icons with unexpected markup, refusing to vendor it: {}",
                style,
                unsafe_icons.join(", ")
            ))));
        }

        Ok(())
    }

    fn safe_symbol(&self, symbol_node: &roxmltree::Node) -> bool {
        let id = symbol_node.attribute("id").unwrap_or("");
        if !ICON_ID.is_match(id) {
            return false;
        }

        let mut is_safe = true;
        for node in symbol_node.descendants() {
            if node.is_text() {
                if !node.text().unwrap_or("").trim().is_empty() {
                    is_safe = false;
                    break;
                }
            } else if node.is_element() {
                let name = node.tag_name().name();
                if name == "symbol" {
                    for attr in node.attributes() {
                        let n = attr.name();
                        if n != "id" && n != "viewBox" {
                            is_safe = false;
                            break;
                        }
                    }
                } else if name == "path" {
                    for attr in node.attributes() {
                        if attr.name() != "d" {
                            is_safe = false;
                            break;
                        }
                    }
                } else {
                    is_safe = false;
                    break;
                }
            }
        }

        is_safe
    }

    fn legacy_sprite(
        &self,
        style: &str,
        upstream_symbols: &HashMap<String, String>,
        _upstream_xml: &str,
        aliases: &HashMap<String, String>,
    ) -> Result<Option<String>, Box<dyn std::error::Error>> {
        let mut candidates = HashMap::new();

        if let Some(content) = self.read(&self.legacy_path(style))? {
            candidates.extend(self.symbols(&content));
        }
        if let Some(content) = self.read(&self.current_path(style))? {
            candidates.extend(self.symbols(&content));
        }

        let mut to_process: Vec<_> = candidates
            .into_iter()
            .filter(|(id, _)| !upstream_symbols.contains_key(id))
            .collect();

        to_process.sort_by(|a, b| a.0.cmp(&b.0));

        let mut entries = Vec::new();

        for (id, symbol_xml) in to_process {
            let successor = aliases.get(&id);
            if let Some(succ) = successor {
                if let Some(successor_symbol) = upstream_symbols.get(succ) {
                    let new_xml = successor_symbol.replacen(
                        &format!(r#"id="{}""#, succ),
                        &format!(r#"id="{}""#, id),
                        1,
                    );
                    entries.push((format!("{}: renamed to {}", id, succ), new_xml));
                    continue;
                }
            }
            entries.push((
                format!("{}: removed, previous artwork kept", id),
                symbol_xml,
            ));
        }

        if entries.is_empty() {
            return Ok(None);
        }

        let mut out = String::from(LEGACY_HEADER);
        for (comment, xml) in entries {
            out.push_str(&format!("<!-- {} -->\n{}\n", comment, xml));
        }
        out.push_str("</svg>\n");

        Ok(Some(out))
    }

    fn symbols(&self, sprite: &str) -> HashMap<String, String> {
        let mut map = HashMap::new();
        if let Ok(doc) = Document::parse(sprite) {
            for node in doc.descendants().filter(|n| n.has_tag_name("symbol")) {
                if let Some(id) = node.attribute("id") {
                    let range = node.range();
                    let xml = sprite[range].to_string();
                    map.insert(id.to_string(), xml);
                }
            }
        }
        map
    }

    fn aliases(&self) -> Result<HashMap<String, String>, Box<dyn std::error::Error>> {
        let path = self.package_path.join("metadata/icon-families.json");
        let content = fs::read_to_string(&path)?;
        let json: serde_json::Value = serde_json::from_str(&content)?;

        let mut map = HashMap::new();
        if let Some(obj) = json.as_object() {
            for (id, val) in obj {
                if let Some(aliases) = val.get("aliases") {
                    if let Some(names) = aliases.get("names").and_then(|n| n.as_array()) {
                        for name in names {
                            if let Some(s) = name.as_str() {
                                map.insert(s.to_string(), id.to_string());
                            }
                        }
                    }
                }
            }
        }
        Ok(map)
    }

    fn read(&self, path: &Path) -> Result<Option<String>, Box<dyn std::error::Error>> {
        if path.exists() {
            Ok(Some(fs::read_to_string(path)?))
        } else {
            Ok(None)
        }
    }

    fn current_path(&self, style: &str) -> PathBuf {
        self.vendor_path
            .join(CURRENT_DIRECTORY)
            .join(format!("{}.svg", style))
    }

    fn legacy_path(&self, style: &str) -> PathBuf {
        self.vendor_path
            .join(LEGACY_DIRECTORY)
            .join(format!("{}.svg", style))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use tempfile::TempDir;

    #[test]
    fn test_font_awesome_sync() {
        let package_dir = TempDir::new().unwrap();
        let vendor_dir = TempDir::new().unwrap();

        let sprites_dir = package_dir.path().join("sprites");
        fs::create_dir_all(&sprites_dir).unwrap();

        let metadata_dir = package_dir.path().join("metadata");
        fs::create_dir_all(&metadata_dir).unwrap();

        // Mock families json
        fs::write(
            metadata_dir.join("icon-families.json"),
            r#"{
                "handshake": {
                    "aliases": {
                        "names": ["handshake-simple"]
                    }
                }
            }"#,
        )
        .unwrap();

        // Mock solid.svg
        fs::write(
            sprites_dir.join("solid.svg"),
            r#"<svg>
<symbol id="handshake" viewBox="0 0 576 512">
<path fill="currentColor" d="M123"/>
</symbol>
<symbol id="new-icon" viewBox="0 0 100 100">
<path d="M456"/>
</symbol>
</svg>"#,
        )
        .unwrap();

        // Other required styles (can be empty)
        fs::write(sprites_dir.join("regular.svg"), "<svg></svg>").unwrap();
        fs::write(sprites_dir.join("brands.svg"), "<svg></svg>").unwrap();

        // Mock existing legacy file
        let legacy_dir = vendor_dir.path().join(LEGACY_DIRECTORY);
        fs::create_dir_all(&legacy_dir).unwrap();
        fs::write(
            legacy_dir.join("solid.svg"),
            r#"<svg>
<symbol id="handshake-simple" viewBox="0 0 576 512"><path d="M000"/></symbol>
<symbol id="removed-icon" viewBox="0 0 50 50"><path d="M999"/></symbol>
</svg>"#,
        )
        .unwrap();

        let sync = FontAwesomeSync::new(package_path(&package_dir), vendor_path(&vendor_dir));

        // Run sync
        assert!(sync.stale_files().unwrap().len() > 0);
        sync.write().unwrap();

        // Verify output
        let current_solid =
            fs::read_to_string(vendor_dir.path().join(CURRENT_DIRECTORY).join("solid.svg"))
                .unwrap();
        assert!(current_solid.contains(r#"id="handshake""#));
        assert!(current_solid.contains(r#"id="new-icon""#));
        assert!(!current_solid.contains("fill=")); // fill should be removed

        let legacy_solid =
            fs::read_to_string(vendor_dir.path().join(LEGACY_DIRECTORY).join("solid.svg")).unwrap();
        assert!(legacy_solid.contains("handshake-simple: renamed to handshake"));
        assert!(legacy_solid.contains(r#"id="handshake-simple""#));
        assert!(legacy_solid.contains("M123")); // updated artwork

        assert!(legacy_solid.contains("removed-icon: removed, previous artwork kept"));
        assert!(legacy_solid.contains(r#"id="removed-icon""#));
        assert!(legacy_solid.contains("M999")); // kept artwork
    }

    fn package_path(dir: &TempDir) -> PathBuf {
        dir.path().to_path_buf()
    }

    fn vendor_path(dir: &TempDir) -> PathBuf {
        dir.path().to_path_buf()
    }
}
